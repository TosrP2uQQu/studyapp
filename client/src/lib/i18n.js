const TABLES = { en, ru, lt };

// t(lang, key, vars) — replaces {name} placeholders. Missing keys fall
// back to English, then to the key itself, never to a crash.
export function t(lang, key, vars) {
  const table = TABLES[lang] || en;
  let s = table[key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

