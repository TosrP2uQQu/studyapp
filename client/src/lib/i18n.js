export function pluralRu(n, one, few, many) {
  const m = Math.abs(n) % 100;
  const d = m % 10;
  if (m > 10 && m < 20) return many;
  if (d > 1 && d < 5) return few;
  if (d === 1) return one;
  return many;
}

export function dayWord(lang, n) {
  if (lang === 'ru') return pluralRu(n, 'день', 'дня', 'дней');
  if (lang === 'lt') return pluralLt(n, 'diena', 'dienos', 'dienų');
  return n === 1 ? 'day' : 'days';
}

export function pluralLt(n, one, few, many) {
  const cat = new Intl.PluralRules('lt').select(Math.abs(n));
  if (cat === 'one') return one;
  if (cat === 'few') return few;
  return many;
}

export function cardWord(lang, n) {
  if (lang === 'ru') return pluralRu(n, 'карточка', 'карточки', 'карточек');
  if (lang === 'lt') return pluralLt(n, 'kortelė', 'kortelės', 'kortelių');
  return n === 1 ? 'card' : 'cards';
}

